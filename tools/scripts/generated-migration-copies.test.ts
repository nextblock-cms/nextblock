import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * /setup applies the migrations it embeds (apps/nextblock/lib/setup/migrations-bundle.ts) wherever
 * libs/db is not on disk, and the public sandbox replays the copy its reset embeds
 * (apps/nextblock/app/api/cron/reset-sandbox/sandboxResetSql.ts) every 15 minutes. Both are generated,
 * and nothing regenerated them when a migration changed: on 2026-11-18 02043, 02044 and 02045 were
 * edited after the last generation, so committing then would have shipped the old functions to /setup
 * and the sandbox (the reset still created the helper that broke its own replay). These checks fail
 * until both are regenerated:
 *
 *   npm run generate:migrations-bundle && npm run generate:sandbox
 *
 * The comparison (tools/scripts/lib/generated-migration-copies.js) copies the generators' rules; the
 * last block holds those rules to the generators' source. No database.
 */

const {
  BUNDLE_COMMAND,
  BUNDLE_FILE,
  SANDBOX_AFTER_MIGRATIONS,
  SANDBOX_COMMAND,
  SANDBOX_FILE,
  bundleEntry,
  bundleFileNames,
  compareMigrationsBundle,
  compareSandboxReset,
  readMigrationsBundleSource,
  readSandboxResetSource,
  sandboxFileNames,
  sandboxFileText,
} = require('./lib/generated-migration-copies.js');

type MigrationFile = { name: string; text: string };

const ROOT = path.resolve(__dirname, '../..');
const MIGRATIONS_DIR = path.join(ROOT, 'libs/db/src/supabase/migrations');

/** The migrations folder's .sql files, as the generators read them. */
function migrationFiles(): MigrationFile[] {
  return readdirSync(MIGRATIONS_DIR)
    .filter((name) => name.endsWith('.sql'))
    .map((name) => ({ name, text: readFileSync(path.join(MIGRATIONS_DIR, name), 'utf8') }));
}

/** A module as generate-migrations-bundle.ts writes it. */
function bundleModule(files: MigrationFile[]): string {
  const texts = new Map(files.map((file) => [file.name, file.text]));
  const entries = bundleFileNames([...texts.keys()]).map((name: string) => bundleEntry(name, texts.get(name)));
  return `// AUTO-GENERATED\n\nexport interface BundledMigration {\n  version: string;\n  name: string;\n  sql: string;\n}\n\nexport const MIGRATIONS_BUNDLE: BundledMigration[] = ${JSON.stringify(entries, null, 2)};\n`;
}

/** SANDBOX_RESET_SQL's text as generate-sandbox-reset.ts builds it (Steps A to F shortened). */
function resetSql(files: MigrationFile[]): string {
  const texts = new Map(files.map((file) => [file.name, file.text]));
  const migrations = sandboxFileNames([...texts.keys()])
    .map((name: string) => `\n\n-- >>> FROM: ${name} <<<\n${sandboxFileText(texts.get(name))}`)
    .join('');
  return `-- AUTO-GENERATED: Sandbox Reset Script.\n  DROP SCHEMA public CASCADE;\n  -- Step C: Execute full schema & seed from production migrations\n${migrations}${SANDBOX_AFTER_MIGRATIONS} Take the API roles' EXECUTE back off every trigger function.\n  INSERT INTO supabase_migrations.schema_migrations (version, name) VALUES\n    ('02000', 'catchup_gen1');\n`;
}

/** The module generate-sandbox-reset.ts writes around that text (its escaping included). */
function resetModule(sql: string): string {
  const escaped = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  return `// AUTO-GENERATED FILE. Do not edit this file directly.\n\nexport const SANDBOX_RESET_SQL = \`\n${escaped}\n\`;\n`;
}

const crlf = (text: string) => text.replace(/\n/g, '\r\n');

const FIXTURE: MigrationFile[] = [
  { name: '02001_baseline_schema.sql', text: "BEGIN;\nCREATE TABLE public.t (id int);\nCOMMIT;\n" },
  { name: '02000_catchup_gen1.sql', text: "-- catch-up\nDO $$ BEGIN RAISE NOTICE 'a `tick` and ${x}'; END $$;\n" },
  { name: '02002_functions.sql', text: "CREATE FUNCTION public.f() RETURNS int LANGUAGE sql AS $$ SELECT 1 $$;\n-- a \\ backslash\n" },
  // Read by one generator only: the bundle takes `<digits>_*.sql`, the reset leaves out "sandbox".
  { name: '02003_sandbox_only.sql', text: 'SELECT 1;\n' },
];

describe('the comparison, on fixtures', () => {
  it('passes a bundle and a reset generated from the same files, a CRLF checkout of the files and of the modules included', () => {
    expect(compareMigrationsBundle(FIXTURE, readMigrationsBundleSource(bundleModule(FIXTURE)))).toEqual([]);
    expect(compareSandboxReset(FIXTURE, readSandboxResetSource(resetModule(resetSql(FIXTURE))))).toEqual([]);

    const checkedOutWithCrlf = FIXTURE.map((file) => ({ ...file, text: crlf(file.text) }));
    expect(compareMigrationsBundle(checkedOutWithCrlf, readMigrationsBundleSource(crlf(bundleModule(FIXTURE))))).toEqual([]);
    expect(compareSandboxReset(checkedOutWithCrlf, readSandboxResetSource(crlf(resetModule(resetSql(FIXTURE)))))).toEqual([]);
  });

  it('reads the modules as JavaScript does: escapes undone, CRLF read as LF, the reset wrapped in one newline each side', () => {
    const sql = resetSql(FIXTURE);
    expect(readSandboxResetSource(crlf(resetModule(sql)))).toBe(`\n${sql}\n`);
    expect(readSandboxResetSource(resetModule(sql))).toContain("'a `tick` and ${x}'");
    expect(readMigrationsBundleSource(bundleModule(FIXTURE)).map((entry: { name: string }) => entry.name)).toEqual([
      '02000_catchup_gen1.sql',
      '02001_baseline_schema.sql',
      '02002_functions.sql',
      '02003_sandbox_only.sql',
    ]);
  });

  it('names a file edited after the generation, and the line where its copy differs', () => {
    const bundle = readMigrationsBundleSource(bundleModule(FIXTURE));
    const reset = readSandboxResetSource(resetModule(resetSql(FIXTURE)));
    const edited = FIXTURE.map((file) =>
      file.name === '02002_functions.sql' ? { ...file, text: file.text.replace('-- a', 'CREATE FUNCTION public.g() RETURNS int LANGUAGE sql AS $$ SELECT 2 $$;\n-- a') } : file
    );

    expect(compareMigrationsBundle(edited, bundle)).toEqual(['02002_functions.sql: the bundle holds another copy of it (differs from line 2)']);
    expect(compareSandboxReset(edited, reset)).toEqual(['02002_functions.sql: the sandbox reset holds another copy of it (differs from line 2)']);
  });

  it('names a file added or removed since the generation, an order that is not the names’ order, and a wrong version', () => {
    const added = [...FIXTURE, { name: '02004_new.sql', text: 'SELECT 4;\n' }];
    expect(compareMigrationsBundle(added, readMigrationsBundleSource(bundleModule(FIXTURE)))).toEqual([
      '02004_new.sql: on disk, missing from the bundle',
    ]);
    expect(compareSandboxReset(added, readSandboxResetSource(resetModule(resetSql(FIXTURE))))).toEqual([
      '02004_new.sql: on disk, missing from the sandbox reset',
    ]);

    const removed = FIXTURE.filter((file) => file.name !== '02002_functions.sql');
    expect(compareMigrationsBundle(removed, readMigrationsBundleSource(bundleModule(FIXTURE)))).toEqual([
      '02002_functions.sql: in the bundle, not a migration file on disk',
    ]);
    expect(compareSandboxReset(removed, readSandboxResetSource(resetModule(resetSql(FIXTURE))))).toEqual([
      '02002_functions.sql: in the sandbox reset, not a migration file on disk',
    ]);

    const bundle = readMigrationsBundleSource(bundleModule(FIXTURE));
    expect(compareMigrationsBundle(FIXTURE, [bundle[1], bundle[0], ...bundle.slice(2)])).toEqual([
      'the bundle lists the files in another order than their names sort',
    ]);
    expect(compareMigrationsBundle(FIXTURE, [{ ...bundle[0], version: '2000' }, ...bundle.slice(1)])).toEqual([
      '02000_catchup_gen1.sql: the bundle gives it version 2000, not 02000',
    ]);
  });

  it('notices text added after the last file of the reset, before its Step C2', () => {
    const reset = readSandboxResetSource(resetModule(resetSql(FIXTURE)));
    const padded = reset.replace(SANDBOX_AFTER_MIGRATIONS, `\nSELECT 'left over';${SANDBOX_AFTER_MIGRATIONS}`);
    expect(compareSandboxReset(FIXTURE, padded)).toEqual(['02002_functions.sql: the sandbox reset holds another copy of it (differs from line 4)']);
  });

  it('refuses a module without the generator’s shape, naming the command to run', () => {
    expect(() => readMigrationsBundleSource('export const MIGRATIONS_BUNDLE = loadThem();\n')).toThrow(
      `${BUNDLE_FILE} declares no MIGRATIONS_BUNDLE array: regenerate it with ${BUNDLE_COMMAND}`
    );
    expect(() => readMigrationsBundleSource('export const MIGRATIONS_BUNDLE = [{ name: "02000_x.sql" }];\n')).toThrow(/without a string "version"/);
    expect(() => readSandboxResetSource('export const SANDBOX_RESET_SQL = `${steps}`;\n')).toThrow(
      `${SANDBOX_FILE} declares no SANDBOX_RESET_SQL string: regenerate it with ${SANDBOX_COMMAND}`
    );
  });
});

describe('the generated copies in the repository', () => {
  const files = migrationFiles();

  it(`${BUNDLE_FILE} embeds every migration file as it is on disk`, () => {
    const bundle = readMigrationsBundleSource(readFileSync(path.join(ROOT, BUNDLE_FILE), 'utf8'));
    expect(compareMigrationsBundle(files, bundle), `${BUNDLE_FILE} is stale: run ${BUNDLE_COMMAND}`).toEqual([]);
  });

  it(`${SANDBOX_FILE} embeds every migration file as it is on disk`, () => {
    const reset = readSandboxResetSource(readFileSync(path.join(ROOT, SANDBOX_FILE), 'utf8'));
    expect(compareSandboxReset(files, reset), `${SANDBOX_FILE} is stale: run ${SANDBOX_COMMAND}`).toEqual([]);
  });
});

describe('the comparison follows the generators', () => {
  /** A generator's source with LF endings (its template literals run with LF whatever the checkout). */
  const generator = (file: string) => readFileSync(path.join(ROOT, 'tools/scripts', file), 'utf8').replace(/\r\n/g, '\n');
  const why = (file: string) => `${file} changed how it picks or embeds the files: change tools/scripts/lib/generated-migration-copies.js to match`;

  // How each module is written (JSON, the template literal's escaping) needs no copy: the readers parse
  // the modules as JavaScript reads them.
  it('generate-migrations-bundle.ts: <digits>_*.sql in name order, the version before the first _, the SQL with LF endings', () => {
    const source = generator('generate-migrations-bundle.ts');
    for (const rule of [
      ".filter((name) => /^\\d+_.*\\.sql$/.test(name))\n  .sort();",
      "version: name.split('_')[0],",
      "sql: readFileSync(path.join(MIGRATIONS_DIR, name), 'utf8').replace(/\\r\\n/g, '\\n'),",
    ]) {
      expect(source, why('generate-migrations-bundle.ts')).toContain(rule);
    }
  });

  it('generate-sandbox-reset.ts: every .sql but "sandbox" ones in name order, LF endings, BEGIN; and COMMIT; stripped, after a FROM line, then Step C2', () => {
    const source = generator('generate-sandbox-reset.ts');
    for (const rule of [
      ".filter(f => f.endsWith('.sql'))",
      ".filter(f => !f.toLowerCase().includes('sandbox'))",
      ".filter(f => f !== '99999999999999_auto_sandbox_reset.sql')\n    .sort();",
      "fs.readFileSync(path.join(MIGRATIONS_DIR, file), 'utf-8').replace(/\\r\\n/g, '\\n');",
      "content = content.replace(/(?:^|\\n)\\s*BEGIN\\s*;/ig, '\\n');",
      "content = content.replace(/(?:^|\\n)\\s*COMMIT\\s*;/ig, '\\n');",
      'concatenatedSql += `\\n\\n-- >>> FROM: ${file} <<<\\n`;\n    concatenatedSql += content;',
      `\${concatenatedSql}${SANDBOX_AFTER_MIGRATIONS}`,
    ]) {
      expect(source, why('generate-sandbox-reset.ts')).toContain(rule);
    }
  });
});
