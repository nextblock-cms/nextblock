/**
 * The names in `names` (one folder's file names) that NextBlock retired, in name order: those of
 * every generation whose catch-up (`GG000_catchup_gen*.sql`) the same folder holds, or a newer one.
 * A folder without such a catch-up is still on the generation those files belong to: none.
 *
 * @param {readonly string[]} names
 * @returns {string[]}
 */
export function retiredMigrationFilesIn(names) {
  const catchups = names
    .map((name) => /^(\d{2})000_catchup_gen\d+\.sql$/.exec(name))
    .filter(Boolean)
    .map((match) => Number.parseInt(match[1], 10));
  if (catchups.length === 0) return [];
  const generation = Math.max(...catchups);
  const retired = new Set(RETIRED_MIGRATIONS.filter((entry) => entry.retiredBy <= generation).flatMap((entry) => entry.files));
  return names.filter((name) => retired.has(name)).sort();
}
