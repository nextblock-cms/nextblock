// The migration files NextBlock shipped in squash generations it has since retired, by exact name.
//
// A standalone project (`npm create nextblock`) keeps every migration file it was scaffolded with in
// supabase/migrations, and each `npm run update` only ADDS the release's files there, so a project
// scaffolded before a squash still holds the retired generation's files beside the current one. No
// applier needs them: the current generation's catch-up (GG000) carries their SQL and replays what a
// database lacks, deciding from the versions its history records. In that folder they can only do harm:
// over an empty history the appliers refuse to run while one is listed (migrate-core's
// emptyHistoryRefusal), and a retired file whose version is not recorded runs again as written.
//
// So `npm run update` moves the files named here out of supabase/migrations into
// supabase/migrations-retired, which nothing reads, once the folder holds the catch-up of the
// generation that retired them (setAsideRetiredMigrations in ../update.mjs). Exact names, never a
// version range: the folder also holds the project's own migrations, and NextBlock's oldest files
// carry timestamps just like a project's (20250513194738_…), while generations 0 and 1 reused the
// same zero-padded numbers under different names (00000000000004_setup_media.sql,
// 00000000000004_default_logo_email_safe.sql).
//
// Squash runbook (docs/04 → "Squashing migrations"): append the retired folder's names in a new entry
// whose `retiredBy` is the new generation. retired-migrations.test.mjs fails while a file the current
// catch-up replays is missing here, or a name here is still in libs/db/src/supabase/migrations.
//
// Plain data, no imports, so the updater can import it next to itself in any project.

